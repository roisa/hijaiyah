#!/usr/bin/env node
/* Builds tools/rekam/rekam-data.js — the clip list for the recording page (tools/rekam/index.html) and the
   listening page (tools/rekam/dengar.html) — from clips-huruf.json, clips-kata.json and clips-lines.json.
   Every clip the game can play from a file, with the exact file the manifests point at, so a recorded take
   replaces the TTS clip 1:1 (tools/voice/import-recordings.sh).
     node tools/voice/build-rekam-data.js          (build-clips.js runs it too)
   Row: {id, s: page section (huruf | kata | id | en), g: group, t: text, h: hint, src: on-screen text when it
         differs, l: lang (ar / id / en), f: target file (audio/<folder>/<id>.mp3), m: manifest (H | X | L),
         key: the manifest key (HIJ_VOICE / HJ_VOICE_EXTRA: the Arabic text; HJ_LINES: "lang|normalised text")} */
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const read = f => { const p = path.join(__dirname, f); return fs.existsSync(p) ? JSON.parse(fs.readFileSync(p, 'utf8')) : []; };
const SECTIONS = [
  { s: 'huruf', id: 'Huruf (rekam ulang)', en: 'Letters (re-record)', ic: '🔤' },
  { s: 'kata', id: 'Kata Arab', en: 'Arabic words', ic: '📖' },
  { s: 'id', id: 'Kalimat Mo · ID', en: "Mo's lines · ID", ic: '🇮🇩' },
  { s: 'en', id: 'Kalimat Mo · EN', en: "Mo's lines · EN", ic: '🇬🇧' },
];
const DIR = { huruf: ['huruf', 'H'], kata: ['extra', 'X'], lines: ['lines', 'L'] };
const seen = new Set(), rows = [];
for (const x of [...read('clips-huruf.json'), ...read('clips-kata.json'), ...read('clips-lines.json')]) {
  if (!DIR[x.sec]) throw new Error('unknown sec ' + x.sec + ' (' + x.id + ')');
  if (!/^[A-Za-z0-9_-]+$/.test(x.id)) throw new Error('bad id ' + x.id);
  if (seen.has(x.id)) throw new Error('duplicate id ' + x.id);
  seen.add(x.id);
  const l = x.lang || 'ar', s = x.sec === 'lines' ? l : x.sec;
  const r = { id: x.id, s, g: x.g || '', t: x.t, h: x.h || '', l, f: 'audio/' + DIR[x.sec][0] + '/' + x.id + '.mp3', m: DIR[x.sec][1], key: x.sec === 'huruf' ? x.t : x.key };
  if (x.src) r.src = x.src;
  rows.push(r);
}
const order = SECTIONS.map(x => x.s);
rows.sort((a, b) => order.indexOf(a.s) - order.indexOf(b.s));
const counts = SECTIONS.map(x => x.s + ' ' + rows.filter(r => r.s === x.s).length).join(', ');
fs.mkdirSync(path.join(ROOT, 'tools', 'rekam'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'tools', 'rekam', 'rekam-data.js'),
  '/* Clip list for tools/rekam/index.html and dengar.html (generated by tools/voice/build-rekam-data.js; do not edit).\n   ' +
  rows.length + ' clips: ' + counts + ' */\n' +
  'window.REKAM_SECTIONS=' + JSON.stringify(SECTIONS) + ';\n' +
  'window.REKAM=[\n' + rows.map(r => JSON.stringify(r)).join(',\n') + '\n];\n');
console.log('wrote tools/rekam/rekam-data.js (' + rows.length + ' clips: ' + counts + ')');
