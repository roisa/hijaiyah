#!/usr/bin/env node
/* Writes sw.js with every file the game needs, so it works offline after the first visit.
   Bump VERSION when shipping changed art or audio (CLAUDE.md rule from Baby Mo). */
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, "..");
const VERSION = "bmh-v16";
const dirs = ["css", "js", "assets", "audio/huruf", "audio/extra", "audio/lines", "audio/quran"];
// audio/extra (Arabic words) and audio/lines (Mo's lines): only their voice.js is precached; the mp3s (hundreds) are
// cached the first time they play, under their full URL with ?v=, so a new take (?v=rec1) is fetched fresh.
const LAZY = /^audio\/(extra|lines)\/.*\.mp3$/;
let files = ["./", "index.html", "manifest.webmanifest"];
function walk(d) { if (!fs.existsSync(path.join(root, d))) return; for (const f of fs.readdirSync(path.join(root, d))) {
  const p = d + "/" + f; if (fs.statSync(path.join(root, p)).isDirectory()) walk(p); else if ((!/\.(md|png)$/.test(f) || /logo/.test(f)) && !LAZY.test(p)) files.push(p); } }
dirs.forEach(walk);
fs.writeFileSync(path.join(root, "sw.js"), `/* generated by tools/build-sw.js */
const CACHE = "${VERSION}";
const SHELL = ${JSON.stringify(files, null, 0)};
self.addEventListener("install", e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(SHELL)).then(() => self.skipWaiting())); });
self.addEventListener("activate", e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener("fetch", e => {
  const u = new URL(e.request.url);
  if (e.request.method !== "GET" || u.origin !== location.origin) return;
  if (/\\/audio\\/(extra|lines)\\/[^/]+\\.mp3$/.test(u.pathname))       // voice clips: cache on first play (exact URL incl. ?v=)
    return e.respondWith(caches.open(CACHE).then(c => c.match(e.request).then(r => r || fetch(e.request).then(res => {
      if (res.ok && res.status === 200) c.put(e.request, res.clone()); return res; }))));
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then(r => r || fetch(e.request)));
});
`);
console.log("sw.js:", files.length, "files");
